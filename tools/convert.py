# Turbo C colour -> palette entry 16+n (the 16 CGA colours set up in startup.asm)
TC_COLOURS = ["BLACK", "BLUE", "GREEN", "CYAN", "RED", "MAGENTA", "BROWN", "LIGHTGRAY",
              "DARKGRAY", "LIGHTBLUE", "LIGHTGREEN", "LIGHTCYAN", "LIGHTRED",
              "LIGHTMAGENTA", "YELLOW", "WHITE"]


def read(name):
    return open(os.path.join(SRC, name), encoding="latin-1").read()


def strip_comments(text):
    return re.sub(r"/\*.*?\*/", " ", text, flags=re.S)


def defines(*files):
    out = {}
    for f in files:
        for m in re.finditer(r"^#define\s+(\w+)\s+(.+)$", strip_comments(read(f)), re.M):
            out[m.group(1)] = m.group(2).strip()
    return out


DEFS = defines("CONSTANT.H", "MONSTER.H")
DEFS.update({c: str(i) for i, c in enumerate(TC_COLOURS)})


def value(expr):
    """Evaluate a C constant expression made of numbers, #defines and | + - ( )."""
    expr = expr.strip()
    for _ in range(10):
        new = re.sub(r"\b([A-Za-z_]\w*)\b", lambda m: "(" + DEFS[m.group(1)] + ")" if m.group(1) in DEFS else m.group(1), expr)
        if new == expr:
            break
        expr = new
    expr = re.sub(r"(\b0x[0-9A-Fa-f]+|\b\d+)[LlUu]+\b", r"\1", expr)
    return int(eval(expr, {"__builtins__": {}}))


def char_value(tok):
    tok = tok.strip()
    m = re.fullmatch(r"'(\\?.)'", tok)
    if not m:
        raise ValueError(tok)
    c = m.group(1)
    return ord({"\\\\": "\\", "\\'": "'", "\\n": "\n"}.get(c, c[-1]))


def split_top(s, sep=","):
    """Split on sep at bracket depth 0, ignoring separators inside quotes."""
    parts, depth, cur, q, esc = [], 0, "", None, False
    for ch in s:
        if q:
            cur += ch
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == q:
                q = None
            continue
        if ch in "\"'":
            q = ch
        elif ch in "({":
            depth += 1
        elif ch in ")}":
            depth -= 1
        if ch == sep and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur)
    return [p.strip() for p in parts]


def table_entries(text, start):
    """Top-level {...} entries of the array initialiser beginning at start."""
    text = strip_comments(text[text.index(start):])
    text = re.sub(r"#ifdef\s+TC_COLOR|#endif|#else", "", text)
    body = text[text.index("{") + 1:]
    entries, depth, cur, q, esc = [], 0, "", None, False
    for ch in body:
        if q:                                        # inside '...' or "...": no brackets
            cur += ch
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == q:
                q = None
            continue
        if ch in "\"'" and depth >= 1:
            q = ch
            cur += ch
            continue
        if ch == "{":
            depth += 1
            if depth == 1:
                cur = ""
                continue
        elif ch == "}":
            depth -= 1
            if depth == 0:
                entries.append(cur)
                continue
            if depth < 0:
                break
        if depth >= 1:
            cur += ch
    return entries


def asm_string(s):
    return '"' + s.replace('"', '""') + '"'


def db_name(name, room):
    raw = name.encode("latin-1")[:room - 1]
    return raw + bytes(room - len(raw))


def db_lines(data, comment):
    out = [f"\t; {comment}"]
    for i in range(0, len(data), 16):
        out.append("\tdb " + ",".join(str(b) for b in data[i:i + 16]))
    return out


# ------------------------------------------------------------------ monsters

def monsters():
    src = read("MONSTERS.C")
    attacks = []
    for e in table_entries(src, "monster_attacks["):
        attacks.append([value(x) for x in split_top(e)])
    races = []
    for e in table_entries(src, "creature_type c_list["):
        f = split_top(e)
        name = f[0].strip('"')
        cmove, spells, cdefense, spells2, spells3 = (value(x) for x in f[1:6])
        mexp, sleep, aaf, ac, speed = (value(x) for x in f[6:11])
        cchar = char_value(f[11])
        hd = [value(x) for x in split_top(f[12].strip("{}"))]
        dam = [value(x) for x in split_top(f[13].strip("{}"))]
        level, rarity = value(f[14]), value(f[15])
        colour = value(f[16]) if len(f) > 16 else 15
        races.append(dict(name=name, cmove=cmove, spells=spells | spells2 | spells3, cdefense=cdefense,
                          mexp=mexp, sleep=sleep, aaf=aaf, ac=ac, speed=speed, char=cchar, hd=hd,
                          attacks=[attacks[a] for a in dam if a], level=level, rarity=rarity,
                          colour=colour))
    return races


def resists(r):
    """R_RESIST: what elements it shrugs off, and what hurts it"""
    bits = 0
    for bit, flag in enumerate(("IM_FROST", "IM_FIRE", "IM_LIGHTNING", "IM_POISON", "IM_ACID",
                                "HURT_LIGHT", "HURT_ROCK")):
        if r["cdefense"] & value(flag):
            bits |= 1 << bit
    return bits


def race_record(r):
    move = 0
    for bit, flag in ((0, "MV_ONLY_ATT"), (1, "MV_ATT_NORM"), (2, "MV_20"), (3, "MV_40"),
                      (4, "MV_75"), (6, "THRO_DR")):
        if r["cmove"] & value(flag):
            move |= 1 << bit
    if r["cdefense"] & value("GROUP"):
        move |= 1 << 5
    flags = 0
    for bit, (field, flag) in enumerate((("cdefense", "UNIQUE"), ("cdefense", "MAX_HP"),
                                         ("cmove", "MV_INVIS"), ("cdefense", "EVIL"),
                                         ("cdefense", "UNDEAD"), ("cdefense", "DEMON"),
                                         ("cdefense", "NO_INFRA"), ("cdefense", "CHARM_SLEEP"))):
        if r[field] & value(flag):
            flags |= 1 << bit
    rec = bytearray(RACE_SIZE)
    exp = min(r["mexp"], 65535)
    rec[0:16] = bytes([r["char"], (16 + (r["colour"] or 15)) * 2, move, exp & 255, exp >> 8,
                       min(r["sleep"], 255), min(r["aaf"], 255), min(r["ac"], 255),
                       min(r["speed"], 255), r["hd"][0], r["hd"][1], min(r["level"], 255),
                       min(r["rarity"], 255), flags,
                       (1 if r["cmove"] & 0x80000000 else 0) | (2 if r["cmove"] & value("CM_PHASE") else 0)
                       | (4 if r["cdefense"] & value("BREAK_WALL") else 0)
                       | sum(8 << i for i, f in enumerate(("ANIMAL", "ORC", "DRAGON", "TROLL", "GIANT"))
                             if r["cdefense"] & value(f)),
                       resists(r)])
    for i, a in enumerate(r["attacks"][:4]):
        rec[16 + i * 4:20 + i * 4] = bytes(a)
    rec[RACE_NAME_OFS:] = db_name(r["name"], RACE_SIZE - RACE_NAME_OFS)
    return bytes(rec)


# ------------------------------------------------------------------- objects

# tval -> (class, equipment) for the kinds the game can use so far
CLASSES = {"TV_FOOD": 1, "TV_POTION1": 2, "TV_POTION2": 2,
           "TV_SCROLL1": 3, "TV_SCROLL2": 3,
           "TV_WAND": 4, "TV_STAFF": 5, "TV_ROD": 6,
           "TV_SWORD": 7, "TV_HAFTED": 7, "TV_POLEARM": 7,
           "TV_SOFT_ARMOR": 8, "TV_HARD_ARMOR": 8, "TV_SHIELD": 9, "TV_HELM": 10,
           "TV_CLOAK": 11, "TV_GLOVES": 12, "TV_BOOTS": 13,
           "TV_AMULET": 14, "TV_RING": 15}
DEVICE_NOUN = {4: "Wand", 5: "Staff", 6: "Rod", 14: "Amulet", 15: "Ring"}
# scroll effects that wait for later milestones: glyphs, traps, acquirement
SCROLL_LATER = {"TV_SCROLL1": 0x00002000 | 0x00200000,
                "TV_SCROLL2": 0x00000400 | 0x00000800}
# potion flag bits the game understands: Cure Light/Serious/Critical Wounds
HEAL_DICE = {0x00001000: 2, 0x00002000: 4, 0x00004000: 6}


def objects():
    out = []
    for i, e in enumerate(table_entries(read("TREASURE.C"), "treasure_type object_list[")):
        f = split_top(e)
        name = f[0].strip('"')
        tval_name = f[2].strip()
        rec = dict(index=i, name=name, flags=value(f[1]), tval_name=tval_name, tval=value(tval_name),
                   char=char_value(f[3]), p1=value(f[4]), cost=value(f[5]), subval=value(f[6]),
                   number=value(f[7]), weight=value(f[8]), tohit=value(f[9]), todam=value(f[10]),
                   ac=value(f[11]), toac=value(f[12]),
                   dice=[value(x) for x in split_top(f[13].strip("{}"))],
                   level=value(f[14]), rare=value(f[15]), flags2=value(f[16]),
                   colour=value(f[17]) if len(f) > 17 else 0)
        out.append(rec)
    return out


def usable(o):
    cls = CLASSES.get(o["tval_name"])
    if not cls:
        return None
    if cls == 1 and o["flags"]:                     # food with magical effects
        return None
    if cls == 3 and o["flags"] & SCROLL_LATER[o["tval_name"]]:
        return None
    return cls


def display_name(o, cls):
    name = o["name"]
    if cls == 2:
        name = "& Potion~ of " + name
    elif cls == 3:
        name = "& Scroll~ of " + name
    elif cls in (14, 15):                            # (they never stack)
        name = f"& {DEVICE_NOUN[cls]} of " + name
    elif cls in DEVICE_NOUN:
        name = f"& {DEVICE_NOUN[cls]}~ of " + name
    return name


def device_charges():
    """magic_treasure's p1 = randint(range) + base for each wand and staff
    subval, and the staffs whose level it changes"""
    src = read("MISC1.C")
    start = src.index("void magic_treasure")
    out = {}
    for tv in ("TV_WAND", "TV_STAFF"):
        a = src.index(f"case {tv}:", start)
        b = src.index("break;\n\n", a) if False else src.index("default", a)
        body = src[a:b]
        table = {}
        for m in re.finditer(r"case (\d+):\s*t_ptr->p1 = randint\((\d+)\)\s*\+\s*(\d+);(\s*t_ptr->level = (\d+);)?", body):
            table[int(m.group(1))] = (int(m.group(2)), int(m.group(3)), int(m.group(5)) if m.group(5) else None)
        out[tv] = table
    return out


CHARGES = None


def kind_record(o, cls):
    name = display_name(o, cls)
    article = name.startswith("& ")
    if article:
        name = name[2:]
    effect = 0                                       # equipment: what magic_treasure
    if o["name"] == "& Whip":                        # treats specially
        effect |= 1
    if o["name"] == "& Robe":
        effect |= 2
    if o["name"].startswith(("Mithril", "Adamantite")):
        effect |= 4
    if o["name"] == "& Pair of Metal Shod Boots":
        effect |= 8
    colour = o["colour"] or 15                       # (potions take their flavour's colour)
    rec = bytearray(KIND_SIZE)
    rec[0:16] = bytes([o["char"], (16 + colour) * 2, cls, effect, min(o["level"], 255),
                       o["weight"] & 255, o["weight"] >> 8, o["dice"][0], o["dice"][1],
                       o["ac"] & 255, o["tohit"] & 255, o["todam"] & 255,
                       o["p1"] & 255, (o["p1"] >> 8) & 255, 1 if article else 0, o["tval"]])
    cost = min(max(o["cost"], 0), 65535)               # (a few artifacts cost more)
    rec[16:18] = bytes([cost & 255, cost >> 8])
    flags = o["flags"] & 0xFFFFFFFF
    rec[18:22] = flags.to_bytes(4, "little")         # effects: bit n = case n+1
    rec[22] = o["subval"] & 63                       # flavour slot
    rec[23] = 1 if o["tval_name"] in ("TV_POTION2", "TV_SCROLL2") else 0
    if o["tval_name"] in ("TV_WAND", "TV_STAFF"):     # p1: charge range, base
        rng, base, lev = CHARGES[o["tval_name"]][o["subval"] & 63]
        rec[12:14] = bytes([rng, base])
        if lev is not None:
            rec[4] = lev
    elif o["tval_name"] == "TV_ROD":
        rec[12:14] = bytes([0, 0])
    elif cls in (14, 15):                            # p1: a stat, or -5 if cursed
        rec[12:14] = bytes([o["p1"] & 255, 255 if o["p1"] < 0 else 0])
    rec[24] = o["toac"] & 255                        # base magical AC
    rec[25] = magic_class(o)                         # how magic_treasure treats it
    rec[26:30] = (o["flags2"] & 0xFFFFFFFF).to_bytes(4, "little")
    rec[KIND_NAME_OFS:] = db_name(name, KIND_SIZE - KIND_NAME_OFS)
    return bytes(rec)


def magic_class(o):
    """MC_ class for magic_treasure: 1 body armour/shields, 2 dragon armour,
    3 weapons, 4 gloves, 5 boots, 6 helms, 7 cloaks, 9 rings, 10 amulets,
    0 anything else"""
    t = o["tval_name"]
    if t in ("TV_SHIELD", "TV_HARD_ARMOR", "TV_SOFT_ARMOR"):
        return 2 if "Dragon Scale" in o["name"] else 1
    if t == "TV_HELM" and 6 <= o["subval"] <= 8:
        return 8                                     # crowns: more often magical
    return {"TV_HAFTED": 3, "TV_POLEARM": 3, "TV_SWORD": 3, "TV_GLOVES": 4,
            "TV_BOOTS": 5, "TV_HELM": 6, "TV_CLOAK": 7, "TV_RING": 9,
            "TV_AMULET": 10}.get(t, 0)


def main():
    global CHARGES
    CHARGES = device_charges()
    races = monsters()
    objs = objects()
    max_dungeon_obj = value("MAX_DUNGEON_OBJ")
    gold_start = max_dungeon_obj + value("OBJ_GOLD_LIST") - value("MAX_DUNGEON_OBJ")
    note = NOTICE.format(src=os.path.basename(os.path.abspath(SRC)))

    # races: all of them, in c_list order (sorted by level)
    lines = [note, f"; {len(races)} races, {RACE_SIZE} bytes each, {8192 // RACE_SIZE} per 8K page", ""]
    for i, r in enumerate(races):
        lines += db_lines(race_record(r), f"{i}: {r['name']} (level {r['level']})")
    open(os.path.join(OUT, "races.asm"), "w").write("\n".join(lines) + "\n")

    # kinds: one per distinct usable object name (copies of an object at
    # different depths share a kind, so they stack); dungeon objects only
    kinds, kind_of = [], {}
    alloc = []                                       # (level, kind, rare) per dungeon object
    for i, o in enumerate(objs[:max_dungeon_obj + 23]):  # + the store-only objects
        cls = usable(o)
        if not cls:
            continue
        key = (o["name"], o["tval"])
        if key not in kind_of:
            kind_of[key] = len(kinds)
            kinds.append((o, cls))
        if i < max_dungeon_obj:
            alloc.append((o["level"], kind_of[key], o["rare"]))
    assert len(kinds) < 512, "kind numbers are 9 bits"
    lines = [note, f"; {len(kinds)} usable item kinds, {KIND_SIZE} bytes each", ""]
    for i, (o, cls) in enumerate(kinds):
        lines += db_lines(kind_record(o, cls), f"{i}: {display_name(o, cls)} (level {o['level']})")
    open(os.path.join(OUT, "kinds.asm"), "w").write("\n".join(lines) + "\n")

    # tables used by the level overlay
    alloc.sort(key=lambda a: a[0])
    t_level = [sum(1 for a in alloc if a[0] <= lv) for lv in range(256)]
    m_level = [sum(1 for r in races if r["level"] <= lv) for lv in range(MAX_MONS_LEVEL + 1)]
    gold = objs[gold_start:gold_start + value("MAX_GOLD")]

    def kind_named(fragment, cls):
        for i, (o, c) in enumerate(kinds):
            if fragment in o["name"] and c == cls:
                return i
        raise KeyError(fragment)

    consts = [note,
             f"NUM_RACES\t\tequ {len(races)}",
             f"NUM_KINDS\t\tequ {len(kinds)}",
             f"NUM_ALLOC\t\tequ {len(alloc)}",
             f"KIND_RATION\t\tequ {kind_named('Ration', 1)}",
             f"KIND_SLIME_MOLD\tequ {kind_named('Slime Mold', 1)}",
             f"KIND_CLW\t\tequ {kind_named('Cure Light', 2)}",
             f"KIND_BROADSWORD\tequ {kind_named('Broadsword', 7)}",
             f"KIND_CHAIN_MAIL\tequ {[i for i, (o, c) in enumerate(kinds) if o['name'] == 'Chain Mail'][0]}",
             f"KIND_RING_SPEED\tequ {kind_named('Speed', 15)}",
             ""]
    lines = [note, "; m_level[]: how many races have level <= n (n = 0-99)", "mon_level_table:"]
    for i in range(0, len(m_level), 10):
        lines.append("\tdw " + ",".join(str(v) for v in m_level[i:i + 10]))
    lines += ["", "; t_level[]: how many dungeon objects have level <= n (n = 0-255)", "obj_level_table:"]
    for i in range(0, len(t_level), 16):
        lines.append("\tdw " + ",".join(str(v) for v in t_level[i:i + 16]))
    lines += ["", "; sorted_objects[]: kind (word), rarity and level of each dungeon object", "obj_alloc_table:"]
    for lv, k, rare in alloc:
        lines.append(f"\tdw {k}\n\tdb {rare},{min(lv, 255)}\t\t; {kinds[k][0]['name']}")
    open(os.path.join(OUT, "alloc.asm"), "w").write("\n".join(lines) + "\n")
    lines = consts + ["; the treasures: name, symbol, colour, base value", "gold_table:"]
    for g in gold:
        lines.append(f"\tdw gn_{g['name'].replace(' ', '_')}")
        lines.append(f"\tdb {g['char']},{(16 + (g['colour'] or 14)) * 2},{g['cost']}")
    for nm in sorted({g["name"] for g in gold}):
        lines.append(f"gn_{nm.replace(' ', '_')}:\tdb {asm_string(nm)},0")
    open(os.path.join(OUT, "tables.asm"), "w").write("\n".join(lines) + "\n")

    ego_tables(note)
    player_tables(note, objs, kinds, kind_of)
    flavour_tables(note)
    store_tables(note, objs, kind_of)

    per_page = 8192 // RACE_SIZE
    print(f"{len(races)} races ({(len(races) + per_page - 1) // per_page} pages), "
          f"{len(kinds)} item kinds ({(len(kinds) + per_page - 1) // per_page} pages), "
          f"{len(alloc)} dungeon objects usable, {len(gold)} treasures")


