#!/usr/bin/env python3
"""Convert Angband PC 1.2's monster and object tables into assembler data.

Reads MONSTERS.C and TREASURE.C (plus the #defines in MONSTER.H and
CONSTANT.H) and writes:

  data/races.asm    every monster race, 64-byte records, for the race pages
  data/kinds.asm    the item kinds the game can use, 64-byte records
  data/tables.asm   treasure kinds and constants (resident)
  data/alloc.asm    level tables for picking monsters and items (level overlay)
  data/player.asm   races, classes, starting kits, titles (creation overlay)
  data/blows.asm    blows_table (items overlay)
  data/stores.asm   store owners, race price table, what each store stocks
  data/flavours.asm potion colour names (flavour page)
  data/egos.asm     ego item names and what they do (ego page)

Usage:  tools/convert.py [path to Angband SRC]   (default ~/Downloads/angband-pc1.2/SRC,
        or $ANGBAND_SRC)
"""
